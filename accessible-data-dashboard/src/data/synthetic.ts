/**
 * Seeded, deterministic synthetic data for scenarios the public data cannot
 * cover (missing values, stale data, partial loads, out-of-range values,
 * empty results, errors). Everything produced here is flagged
 * `synthetic: true` and shown with a "Synthetic data" badge in the UI.
 */
import type { Observation, Series, Snapshot, WidgetState } from './types';
import { monthIndexToPeriod, periodToMonthIndex } from './format';

export const SYNTHETIC_SEED = 20261031;

/** mulberry32 — small, fast, deterministic PRNG. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Stable 32-bit hash so each (seed, key) pair has its own stream. */
export function hashString(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export interface SyntheticSeriesSpec {
  id: string;
  label: string;
  /** Mean the series reverts to. */
  level: number;
  /** Starting value. */
  start: number;
  volatility: number;
}

/** Mean-reverting random walk, monthly periods from `from` to `to` inclusive. */
export function generateSeries(spec: SyntheticSeriesSpec, from: string, to: string, seed = SYNTHETIC_SEED): Series {
  const rnd = mulberry32(seed ^ hashString(spec.id));
  const a = periodToMonthIndex(from);
  const b = periodToMonthIndex(to);
  const observations: Observation[] = [];
  let v = spec.start;
  for (let i = a; i <= b; i++) {
    const shock = (rnd() - 0.5) * 2 * spec.volatility;
    v = v + 0.15 * (spec.level - v) + shock;
    observations.push({ period: monthIndexToPeriod(i), value: Math.round(v * 10) / 10 });
  }
  return { id: spec.id, key: `SYNTH.${spec.id}`, label: spec.label, observations };
}

/**
 * Turn a real (or synthetic) snapshot into a synthetic snapshot exhibiting a
 * data state. The shape of the data is preserved; values are regenerated
 * from the seed so synthetic numbers are never mistaken for real ones.
 */
export function simulateState(base: Snapshot, state: WidgetState, seed = SYNTHETIC_SEED): Snapshot {
  const rnd = mulberry32(seed ^ hashString(base.id + state));
  const series: Series[] = base.series.map((s) => {
    const vals = s.observations.map((o) => o.value).filter((v): v is number => v != null);
    const mean = vals.length ? vals.reduce((x, y) => x + y, 0) / vals.length : 1;
    const spread = vals.length ? Math.max(...vals) - Math.min(...vals) : 1;
    let v = vals[0] ?? mean;
    return {
      ...s,
      key: `SYNTH.${s.key}`,
      observations: s.observations.map((o) => {
        v = v + 0.2 * (mean - v) + (rnd() - 0.5) * spread * 0.08;
        const digits = Math.abs(mean) > 1000 ? 0 : 1;
        return { period: o.period, value: Math.round(v * 10 ** digits) / 10 ** digits };
      }),
    };
  });

  /** Prefer series that are visible with the default filters, so simulated issues are on screen. */
  const pick = (prefer: string[], fallback: number) => {
    const i = out.series.findIndex((s) => prefer.includes(s.id));
    return i >= 0 ? i : Math.min(fallback, out.series.length - 1);
  };
  const out: Snapshot = { ...base, source: 'Synthetic', synthetic: true, licence: 'Synthetic data generated by the prototype (seed ' + seed + ').', url: '', series };
  switch (state) {
    case 'partial': {
      // Drop one visible series entirely, and the last 3 observations of another.
      const a = pick(['IT', 'other', 'GBP'], 1);
      const b = pick(['DE', 'consumer', 'CHF'], 2);
      if (out.series[a]) out.series[a] = { ...out.series[a], observations: out.series[a].observations.map((o) => ({ ...o, value: null })) };
      if (out.series[b] && b !== a) out.series[b] = { ...out.series[b], observations: out.series[b].observations.map((o, i, arr) => (i >= arr.length - 3 ? { ...o, value: null } : o)) };
      break;
    }
    case 'stale': {
      // The latest 4 periods were never received: data is months behind the snapshot date.
      out.series = out.series.map((s) => ({ ...s, observations: s.observations.slice(0, -4) }));
      break;
    }
    case 'out-of-range': {
      // Inject one implausible spike (10× the series' typical magnitude).
      const target = out.series[pick(['ES', 'consumer', 'USD'], 1)];
      if (target) {
        const obs = target.observations;
        const i = Math.max(0, obs.length - 2);
        const typical = Math.max(...obs.map((o) => Math.abs(o.value ?? 0)), 1);
        obs[i] = { ...obs[i], value: Math.round(typical * 10 * 10) / 10 };
      }
      break;
    }
    case 'empty-first':
    case 'empty-no-results':
      out.series = [];
      break;
    default:
      break;
  }
  return out;
}

/** A standalone synthetic snapshot (used if a real snapshot file is missing). */
export function syntheticSnapshot(id: Snapshot['id'], specs: SyntheticSeriesSpec[], from: string, to: string, unit: string, unitLabel: string): Snapshot {
  return {
    id, title: `${id} (synthetic)`, source: 'Synthetic', licence: `Synthetic data generated by the prototype (seed ${SYNTHETIC_SEED}).`, url: '',
    retrievedAt: new Date().toISOString(), sourceUpdated: null, frequency: 'M', unit, unitLabel, synthetic: true,
    series: specs.map((s) => generateSeries(s, from, to)),
  };
}
