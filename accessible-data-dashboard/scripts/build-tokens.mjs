#!/usr/bin/env node
// Compiles packages/tokens/tokens.json → src/styles/tokens.css (CSS custom properties).
// Placeholder token set — see DECISIONS.md D-003.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'packages/tokens/tokens.json'), 'utf8'));
const v = (name) => `--${name.replace(/\//g, '-')}`;
const modes = { light: ':root, :root[data-theme="light"]', dark: ':root[data-theme="dark"]', hc: ':root[data-theme="hc"]' };

let css = '/* GENERATED by scripts/build-tokens.mjs from packages/tokens/tokens.json — do not edit. */\n';
for (const [mode, sel] of Object.entries(modes)) {
  css += `${sel} {\n  color-scheme: ${mode === 'light' ? 'light' : 'dark'};\n`;
  for (const [name, vals] of Object.entries(t.color)) css += `  ${v('color/' + name)}: ${vals[mode]};\n`;
  css += '}\n';
}
css += ':root {\n';
for (const [k, px] of Object.entries(t.space)) css += `  --space-${k}: ${px / 16}rem;\n`;
for (const [k, px] of Object.entries(t.radius)) css += `  --radius-${k}: ${px}px;\n`;
for (const [k, s] of Object.entries(t.font.scale)) css += `  --font-${k}-size: ${s.size / 16}rem;\n  --font-${k}-line: ${s.line / s.size};\n  --font-${k}-weight: ${s.weight};\n`;
css += `  --font-family: ${t.font.family};\n`;
for (const [k, px] of Object.entries(t.density.comfortable)) css += `  --density-${k}: ${px / 16}rem;\n`;
css += '}\n:root[data-density="compact"] {\n';
for (const [k, px] of Object.entries(t.density.compact)) css += `  --density-${k}: ${px / 16}rem;\n`;
css += '}\n';
mkdirSync(join(root, 'src/styles'), { recursive: true });
writeFileSync(join(root, 'src/styles/tokens.css'), css);
// Also emit a TS module so charts can read series styling without parsing CSS.
writeFileSync(join(root, 'src/styles/tokens.gen.ts'), `// GENERATED — do not edit.\nexport const colorTokens = ${JSON.stringify(t.color, null, 2)} as const;\nexport const chartTokens = ${JSON.stringify(t.chart, null, 2)} as const;\n`);
console.log('tokens.css + tokens.gen.ts written');
